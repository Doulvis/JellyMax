export type TranslationKey = Key;

export function lang() {
  return getSettings().language;
}

export function locale() {
  return lang() === 'en' ? 'en-US' : 'fr-FR';
}

/** Texte traduit ; les {variables} sont remplacées par les valeurs fournies. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  const dict = lang() === 'en' ? en : fr;
  let s: string = dict[key] || fr[key] || key;
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  }
  return s;
}

const BITRATE_RES = ['', '4K', '1080p', '1080p', '720p', '480p', '360p'];

export function bitrateOptions(): { value: number; label: string }[] {
  return BITRATE_VALUES.map((value, i) => {
    if (i === 0) return { value, label: t('bitrate.auto') };
    const mbps = (value / 1_000_000).toLocaleString(locale());
    return { value, label: `${BITRATE_RES[i]} — ${mbps} ${lang() === 'en' ? 'Mbps' : 'Mb/s'}` };
  });
}
